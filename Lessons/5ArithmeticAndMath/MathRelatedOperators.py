print("Round function : ")
# Round function
A = 3.14
B = 3.5
print(round(A))
print(round(B))

print("Absolute function : ")
# Absolute function = Distance away 0
C = -3
D = 3
print(abs(C))
print(abs(D))

print("Power function : ")
# power function = number * (time)
C = -3
D = 3
print(pow(C, D))
print(pow(2, 5))

print("Maximum function : ")
# Maximum function = Maximum value of values
C = -3
D = 3
print(max(A, B, C, D))

print("Minimum function : ")
# Minimum function = Minimum value of values
C = -3
D = 3
print(min(A, B, C, D))
